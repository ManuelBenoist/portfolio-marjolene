/**
 * generate-redirects.cjs
 *
 * Generates HTML redirect pages for old Wix URLs so that
 * Google-indexed links (e.g. /home, /paintings) land on the
 * correct new pages instead of returning 404.
 *
 * Runs automatically after `nuxt generate`.
 */

const fs = require('fs');
const path = require('path');

const DOMAIN = 'https://marjolene-lasne.com';
const OUTPUT_DIR = path.resolve(__dirname, '../.output/public');

/** Old URL → New URL mapping */
const REDIRECTS = [
  { from: '/home', to: '/' },
  { from: '/paintings', to: '/peintures/' },
  { from: '/artist', to: '/artiste/' },
  { from: '/page2', to: '/peintures/' },
  { from: '/faq-fr', to: '/contact/' },
  { from: '/design-textile', to: '/autres-activites/' },
  { from: '/mon-panier', to: '/contact/' },
  { from: '/vierge', to: '/' },
  { from: '/product-page', to: '/foulards/' },
];

/**
 * Build a minimal HTML page that immediately redirects via
 * <meta http-equiv="refresh"> and includes a canonical link
 * for search-engine crawlers.
 */
function buildRedirectHTML(targetURL) {
  return `<!DOCTYPE html>
<html lang="fr">
<head>
  <meta charset="utf-8">
  <meta http-equiv="refresh" content="0; url=${targetURL}">
  <link rel="canonical" href="${targetURL}">
  <title>Redirection…</title>
</head>
<body>
  <p>Cette page a été déplacée. <a href="${targetURL}">Cliquez ici</a> si vous n'êtes pas redirigé automatiquement.</p>
</body>
</html>`;
}

// ---------------------------------------------------------------------------

if (!fs.existsSync(OUTPUT_DIR)) {
  console.error(`❌  Output directory not found: ${OUTPUT_DIR}`);
  console.error('   Run "npm run generate" first (this script is meant to run after nuxt generate).');
  process.exit(1);
}

console.log('\n🔀  Generating legacy-URL redirects…\n');

let created = 0;
let skipped = 0;

REDIRECTS.forEach(({ from, to }) => {
  if (from === to) {
    console.log(`   ⏭  Skipping loop redirect: ${from} → ${to}`);
    skipped++;
    return;
  }

  const slug = from.replace(/^\//, '');
  const dir = path.join(OUTPUT_DIR, slug);
  const file = path.join(dir, 'index.html');

  // Don't overwrite real pages generated by Nuxt
  if (fs.existsSync(file)) {
    const content = fs.readFileSync(file, 'utf8');
    if (!content.includes('http-equiv="refresh"')) {
      console.log(`   ⚠️  ${from}/index.html already exists (real page) — skipped`);
      skipped++;
      return;
    }
  }

  const targetURL = `${DOMAIN}${to}`;

  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(file, buildRedirectHTML(targetURL));
  console.log(`   ✅  ${from}  →  ${to}`);
  created++;
});

console.log(`\n   Done: ${created} redirect(s) created, ${skipped} skipped.\n`);
